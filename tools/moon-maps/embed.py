#!/usr/bin/env python3
"""Embeds textures/moons/*.jpg into js/data/moonMaps.js as base64 data URIs.
Data URIs work from file:// (double-clicked index.html) where separate image files cannot be used as WebGL textures.
Run from the repository root:  python3 tools/moon-maps/embed.py"""
import base64, glob, os
out = ['// GENERATED by tools/moon-maps/embed.py from textures/moons/*.jpg. Do not edit by hand.',
       '// Credits and licences: textures/moons/CREDITS.md and js/data/moonCredits.js', 'export const MOON_MAP_DATA = {']
total = 0
for f in sorted(glob.glob('textures/moons/*.jpg')):
    b = open(f, 'rb').read(); total += len(b)
    out.append(f"  {os.path.basename(f)[:-4]}: 'data:image/jpeg;base64,{base64.b64encode(b).decode()}',")
out.append('};')
open('js/data/moonMaps.js', 'w').write('\n'.join(out) + '\n')
print('embedded', total // 1024, 'KB of JPEG ->', os.path.getsize('js/data/moonMaps.js') // 1024, 'KB module')
